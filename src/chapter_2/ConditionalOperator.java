package chapter_2;

/**
 * 2.2 Условный оператор
 */

public class ConditionalOperator {

    static void main() {
        int temp = 30;

        if (temp > 20) {
            System.out.println("Включить кондиционер");
        } else {
            System.out.println("Выключить кондиционер");
        }
    }
}
