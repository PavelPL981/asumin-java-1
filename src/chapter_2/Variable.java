package chapter_2;

public class Variable {

    static void main() {
        int x = 100;
        int y = 5 * x;
        int sum = x + y;
        System.out.println(x);
        System.out.println(y);
        System.out.println(sum);

        int a = 10;
        int b = 3;
        int c = a / b;
        int d = a % b;
        System.out.println(c);
        System.out.println(d);

    }
}
